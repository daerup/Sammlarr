using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Roslyn.Providers;

[Generator]
public class SuppliedByGenerator : IIncrementalGenerator
{
	private const string SuppliedByAttributeMetadataName = "Shared.SuppliedByAttribute`1";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var supplied = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				SuppliedByAttributeMetadataName,
				static (node, _) => node is EnumMemberDeclarationSyntax,
				static (ctx, _) => Read(ctx)
			)
			.Collect();

		context.RegisterSourceOutput(supplied, static (spc, members) => Emit(spc, members));
	}

	private static SuppliedMember Read(GeneratorAttributeSyntaxContext context)
	{
		var member = (IFieldSymbol)context.TargetSymbol;
		var target = member.ContainingType;
		var supplierType = (INamedTypeSymbol)context.Attributes[0].AttributeClass!.TypeArguments[0];
		var supplierMembers = Members(supplierType);
		var arguments = context.Attributes[0].ConstructorArguments;
		var suppliers =
			arguments.Length > 0 && arguments[0].Kind == TypedConstantKind.Array
				? arguments[0]
					.Values.Select(value => supplierMembers.FirstOrDefault(supplier => Equals(supplier.Value, value.Value)).Name)
					.Where(name => name is not null)
					.ToImmutableArray()
				: ImmutableArray<string>.Empty;

		return new SuppliedMember(
			Qualified(target),
			target.Name,
			target.ContainingNamespace.ToDisplayString(),
			Members(target).Select(static field => field.Name).ToImmutableArray(),
			Qualified(supplierType),
			supplierMembers.Select(static field => field.Name).ToImmutableArray(),
			member.Name,
			suppliers
		);
	}

	private static ImmutableArray<(string Name, object? Value)> Members(INamedTypeSymbol enumType)
	{
		return enumType
			.GetMembers()
			.OfType<IFieldSymbol>()
			.Where(static field => field.HasConstantValue)
			.OrderBy(static field => Convert.ToInt64(field.ConstantValue))
			.Select(static field => (field.Name, field.ConstantValue))
			.ToImmutableArray();
	}

	private static string Qualified(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

	private static void Emit(SourceProductionContext context, ImmutableArray<SuppliedMember> members)
	{
		foreach (var target in members.GroupBy(static member => member.TargetQualified))
		{
			var first = target.First();
			var suppliersBySource = target.ToDictionary(static member => member.Member, static member => member.Suppliers);
			context.AddSource($"{first.TargetName}Suppliers.g.cs", SourceText.From(Build(first, suppliersBySource), Encoding.UTF8));
		}
	}

	private static string Build(SuppliedMember shape, Dictionary<string, ImmutableArray<string>> suppliersBySource)
	{
		var valueSet = "global::Shared.Collections.ValueSet";
		var reverse = $"Supplied{shape.TargetName}s";
		var sb = new StringBuilder("// <auto-generated />\n#nullable enable\n#pragma warning disable CS8524\nusing System.Runtime.CompilerServices;\n\n");
		sb.Append("namespace ").Append(shape.TargetNamespace).Append(";\n\npublic static class ").Append(shape.TargetName).Append("Suppliers\n{\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static ")
			.Append(valueSet)
			.Append('<')
			.Append(shape.SupplierQualified)
			.Append("> SuppliedBy(this ")
			.Append(shape.TargetQualified)
			.Append(" value) =>\n\t\tvalue switch\n\t\t{\n");
		foreach (var source in shape.TargetMembers)
		{
			var suppliers = suppliersBySource.TryGetValue(source, out var named) ? named : ImmutableArray<string>.Empty;
			sb.Append("\t\t\t").Append(shape.TargetQualified).Append('.').Append(source).Append(" => [");
			sb.Append(string.Join(", ", suppliers.Select(supplier => $"{shape.SupplierQualified}.{supplier}")));
			sb.Append("],\n");
		}
		sb.Append("\t\t};\n\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static ")
			.Append(valueSet)
			.Append('<')
			.Append(shape.TargetQualified)
			.Append("> ")
			.Append(reverse)
			.Append("(this ")
			.Append(shape.SupplierQualified)
			.Append(" supplier) =>\n\t\tsupplier switch\n\t\t{\n");
		foreach (var supplier in shape.SupplierMembers)
		{
			var sources = suppliersBySource.Where(pair => pair.Value.Contains(supplier)).Select(pair => pair.Key);
			sb.Append("\t\t\t").Append(shape.SupplierQualified).Append('.').Append(supplier).Append(" => [");
			sb.Append(string.Join(", ", shape.TargetMembers.Where(sources.Contains).Select(source => $"{shape.TargetQualified}.{source}")));
			sb.Append("],\n");
		}
		sb.Append("\t\t};\n\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static ")
			.Append(valueSet)
			.Append('<')
			.Append(shape.TargetQualified)
			.Append("> ")
			.Append(reverse)
			.Append("(this global::System.Collections.Generic.IEnumerable<")
			.Append(shape.SupplierQualified)
			.Append("> suppliers) =>\n\t\t[.. global::System.Linq.Enumerable.Distinct(global::System.Linq.Enumerable.SelectMany(suppliers, static supplier => ")
			.Append(reverse)
			.Append("(supplier)))];\n");

		sb.Append("}\n");
		return sb.ToString();
	}

	private readonly struct SuppliedMember
	{
		public SuppliedMember(
			string targetQualified,
			string targetName,
			string targetNamespace,
			ImmutableArray<string> targetMembers,
			string supplierQualified,
			ImmutableArray<string> supplierMembers,
			string member,
			ImmutableArray<string> suppliers
		)
		{
			TargetQualified = targetQualified;
			TargetName = targetName;
			TargetNamespace = targetNamespace;
			TargetMembers = targetMembers;
			SupplierQualified = supplierQualified;
			SupplierMembers = supplierMembers;
			Member = member;
			Suppliers = suppliers;
		}

		public string TargetQualified { get; }
		public string TargetName { get; }
		public string TargetNamespace { get; }
		public ImmutableArray<string> TargetMembers { get; }
		public string SupplierQualified { get; }
		public ImmutableArray<string> SupplierMembers { get; }
		public string Member { get; }
		public ImmutableArray<string> Suppliers { get; }
	}
}
