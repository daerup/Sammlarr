using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Roslyn.Providers;

[Generator]
public class SuppliedByGenerator : IIncrementalGenerator
{
	private const string SuppliedByAttributeMetadataName = "Shared.SuppliedByAttribute`1";

	private const string ValueSet = "global::Shared.Collections.ValueSet";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var supplied = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				SuppliedByAttributeMetadataName,
				static (node, _) => node is EnumMemberDeclarationSyntax,
				static (ctx, _) => Read(ctx)
			)
			.Collect();

		context.RegisterSourceOutput(supplied, static (spc, members) => Emit(spc, members));
	}

	private static SuppliedMember Read(GeneratorAttributeSyntaxContext context)
	{
		var member = (IFieldSymbol)context.TargetSymbol;
		var target = member.ContainingType;
		var supplierType = (INamedTypeSymbol)context.Attributes[0].AttributeClass!.TypeArguments[0];
		var supplierMembers = Members(supplierType);
		var arguments = context.Attributes[0].ConstructorArguments;
		var named = arguments.Length > 0 && arguments[0].Kind == TypedConstantKind.Array ? arguments[0].Values : [];
		ImmutableArray<string> suppliers =
		[
			.. named.Select(value => supplierMembers.FirstOrDefault(supplier => Equals(supplier.Value, value.Value)).Name).Where(name => name is not null),
		];

		return new SuppliedMember(
			Qualified(target),
			target.Name,
			target.ContainingNamespace.ToDisplayString(),
			[.. Members(target).Select(static field => field.Name)],
			Qualified(supplierType),
			[.. supplierMembers.Select(static field => field.Name)],
			member.Name,
			suppliers
		);
	}

	private static ImmutableArray<(string Name, object? Value)> Members(INamedTypeSymbol enumType)
	{
		return
		[
			.. enumType
				.GetMembers()
				.OfType<IFieldSymbol>()
				.Where(static field => field.HasConstantValue)
				.OrderBy(static field => Convert.ToInt64(field.ConstantValue, CultureInfo.InvariantCulture))
				.Select(static field => (field.Name, field.ConstantValue)),
		];
	}

	private static string Qualified(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

	private static void Emit(SourceProductionContext context, ImmutableArray<SuppliedMember> members)
	{
		foreach (var target in members.GroupBy(static member => member.TargetQualified, StringComparer.Ordinal))
		{
			var first = target.First();
			var suppliersBySource = target.ToDictionary(static member => member.Member, static member => member.Suppliers, StringComparer.Ordinal);
			context.AddSource($"{first.TargetName}Suppliers.g.cs", SourceText.From(Build(first, suppliersBySource), Encoding.UTF8));
		}
	}

	private static string Build(SuppliedMember shape, Dictionary<string, ImmutableArray<string>> suppliersBySource)
	{
		var reverse = $"Supplied{shape.TargetName}s";
		var suppliedBy = string.Join("\n", shape.TargetMembers.Select(source => SuppliersArm(shape, source, suppliersBySource)));
		var supplied = string.Join("\n", shape.SupplierMembers.Select(supplier => SourcesArm(shape, supplier, suppliersBySource)));
		return $$"""
			// <auto-generated />
			#nullable enable
			#pragma warning disable CS8524
			using System.Runtime.CompilerServices;

			namespace {{shape.TargetNamespace}};

			public static class {{shape.TargetName}}Suppliers
			{
				[CompilerGenerated]
				public static {{ValueSet}}<{{shape.SupplierQualified}}> SuppliedBy(this {{shape.TargetQualified}} value) =>
					value switch
					{
			{{suppliedBy}}
					};

				[CompilerGenerated]
				public static {{ValueSet}}<{{shape.TargetQualified}}> {{reverse}}(this {{shape.SupplierQualified}} supplier) =>
					supplier switch
					{
			{{supplied}}
					};

				[CompilerGenerated]
				public static {{ValueSet}}<{{shape.TargetQualified}}> {{reverse}}(this global::System.Collections.Generic.IEnumerable<{{shape.SupplierQualified}}> suppliers) =>
					[.. global::System.Linq.Enumerable.Distinct(global::System.Linq.Enumerable.SelectMany(suppliers, static supplier => {{reverse}}(supplier)))];
			}

			""";
	}

	private static string SuppliersArm(SuppliedMember shape, string source, Dictionary<string, ImmutableArray<string>> suppliersBySource)
	{
		var suppliers = suppliersBySource.TryGetValue(source, out var named) ? named : [];
		var values = string.Join(", ", suppliers.Select(supplier => $"{shape.SupplierQualified}.{supplier}"));
		return $"\t\t\t{shape.TargetQualified}.{source} => [{values}],";
	}

	private static string SourcesArm(SuppliedMember shape, string supplier, Dictionary<string, ImmutableArray<string>> suppliersBySource)
	{
		var sources = suppliersBySource.Where(pair => pair.Value.Contains(supplier, StringComparer.Ordinal)).Select(pair => pair.Key);
		var values = string.Join(", ", shape.TargetMembers.Where(sources.Contains).Select(source => $"{shape.TargetQualified}.{source}"));
		return $"\t\t\t{shape.SupplierQualified}.{supplier} => [{values}],";
	}

	private readonly struct SuppliedMember(
		string targetQualified,
		string targetName,
		string targetNamespace,
		ImmutableArray<string> targetMembers,
		string supplierQualified,
		ImmutableArray<string> supplierMembers,
		string member,
		ImmutableArray<string> suppliers
	)
	{
		public string TargetQualified { get; } = targetQualified;
		public string TargetName { get; } = targetName;
		public string TargetNamespace { get; } = targetNamespace;
		public ImmutableArray<string> TargetMembers { get; } = targetMembers;
		public string SupplierQualified { get; } = supplierQualified;
		public ImmutableArray<string> SupplierMembers { get; } = supplierMembers;
		public string Member { get; } = member;
		public ImmutableArray<string> Suppliers { get; } = suppliers;
	}
}
