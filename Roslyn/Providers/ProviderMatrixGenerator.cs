using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Roslyn.Providers;

[Generator]
public class ProviderMatrixGenerator : IIncrementalGenerator
{
	private const string CapabilitiesAttributeMetadataName = "Shared.CapabilitiesAttribute`1";
	private const string ConvertsToAttributeMetadataName = "Shared.ConvertsToAttribute`1";
	private const string ProviderCapabilityMetadataName = "Domain.Providers.ProviderCapability";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var brands = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				CapabilitiesAttributeMetadataName,
				static (node, _) => node is EnumMemberDeclarationSyntax,
				static (ctx, _) =>
					new Brand(ctx.TargetSymbol.Name, Flags(ctx), ctx.TargetSymbol is IFieldSymbol { ConstantValue: int order } ? order : 0, Description(ctx.TargetSymbol))
			)
			.Collect();

		var matrix = context.CompilationProvider.Select(static (compilation, _) => ReadMatrix(compilation));

		context.RegisterSourceOutput(brands.Combine(matrix), static (spc, pair) => Emit(spc, pair.Left, pair.Right));
	}

	private static int Flags(GeneratorAttributeSyntaxContext context) =>
		context.Attributes[0].ConstructorArguments.Length > 0 && context.Attributes[0].ConstructorArguments[0].Value is int flags ? flags : 0;

	private static string? Description(ISymbol member)
	{
		var description = member
			.GetAttributes()
			.FirstOrDefault(attribute => attribute.AttributeClass?.ToDisplayString() == "System.ComponentModel.DescriptionAttribute");
		return description is not null && description.ConstructorArguments.Length > 0 ? description.ConstructorArguments[0].Value as string : null;
	}

	private static Matrix ReadMatrix(Compilation compilation)
	{
		var capabilityEnum = compilation.GetTypeByMetadataName(ProviderCapabilityMetadataName);
		if (capabilityEnum is null)
		{
			return new Matrix(ImmutableArray<Capability>.Empty, ImmutableArray<Conversion>.Empty);
		}

		var convertsToAttribute = compilation.GetTypeByMetadataName(ConvertsToAttributeMetadataName);
		var capabilities = ImmutableArray.CreateBuilder<Capability>();
		var conversions = ImmutableArray.CreateBuilder<Conversion>();

		foreach (var member in capabilityEnum.GetMembers().OfType<IFieldSymbol>())
		{
			if (member.ConstantValue is not int bit || bit == 0)
			{
				continue;
			}

			capabilities.Add(new Capability(bit, member.Name + "Provider"));

			var convertsTo = member
				.GetAttributes()
				.FirstOrDefault(attribute => SymbolEqualityComparer.Default.Equals(attribute.AttributeClass?.OriginalDefinition, convertsToAttribute));
			if (convertsTo is not null && convertsTo.ConstructorArguments.Length > 0 && convertsTo.ConstructorArguments[0].Value is int targets)
			{
				conversions.Add(new Conversion(bit, targets));
			}
		}

		return new Matrix(capabilities.ToImmutable(), conversions.ToImmutable());
	}

	private static void Emit(SourceProductionContext context, ImmutableArray<Brand> brands, Matrix matrix)
	{
		if (brands.IsDefaultOrEmpty || matrix.Capabilities.IsDefaultOrEmpty)
		{
			return;
		}

		var ordered = brands.OrderBy(static brand => brand.Order).ToList();
		context.AddSource("ProviderEnums.g.cs", SourceText.From(Enums(ordered, matrix.Capabilities), Encoding.UTF8));
		context.AddSource("ProviderConversions.g.cs", SourceText.From(Conversions(ordered, matrix.Capabilities, matrix.Conversions), Encoding.UTF8));
	}

	private static string Enums(List<Brand> brands, ImmutableArray<Capability> capabilities)
	{
		var enums = string.Join(
			"\n\n",
			capabilities.Select(capability => ProviderEnum(capability.EnumName, brands.Where(brand => (brand.Capabilities & capability.Bit) != 0)))
		);
		return $$"""
			// <auto-generated />
			#nullable enable
			using System.ComponentModel;

			namespace Domain.Providers;

			{{enums}}

			""";
	}

	private static string ProviderEnum(string name, IEnumerable<Brand> brands)
	{
		var members = string.Join("\n", brands.Select(Member));
		return $$"""
			public enum {{name}}
			{
			{{members}}
			}
			""";
	}

	private static string Member(Brand brand) => brand.Description is null ? $"\t{brand.Name}," : $"\t[Description(\"{brand.Description}\")]\n\t{brand.Name},";

	private static string Conversions(List<Brand> brands, ImmutableArray<Capability> capabilities, ImmutableArray<Conversion> conversions)
	{
		var toMediaProvider = capabilities.Select(capability => AsMethod(capability.EnumName, "MediaProvider", BrandsWith(brands, capability.Bit)));
		var betweenCapabilities = conversions.SelectMany(conversion => ConversionsBetween(brands, capabilities, conversion));
		var methods = string.Join("\n\n", toMediaProvider.Concat(betweenCapabilities));
		return $$"""
			// <auto-generated />
			#nullable enable
			#pragma warning disable CS8524
			using System.Runtime.CompilerServices;

			namespace Domain.Providers;

			public static class ProviderConversions
			{
			{{methods}}

			}

			""";
	}

	private static IEnumerable<string> ConversionsBetween(List<Brand> brands, ImmutableArray<Capability> capabilities, Conversion conversion)
	{
		var sourceEnum = EnumNameFor(capabilities, conversion.SourceBit);
		if (sourceEnum is null)
		{
			yield break;
		}

		var sourceCount = BrandsWith(brands, conversion.SourceBit).Count;
		foreach (var capability in capabilities.Where(capability => (conversion.TargetBits & capability.Bit) != 0))
		{
			var shared = brands
				.Where(brand => (brand.Capabilities & conversion.SourceBit) != 0 && (brand.Capabilities & capability.Bit) != 0)
				.Select(static brand => brand.Name)
				.ToList();
			if (shared.Count > 0 && shared.Count == sourceCount)
			{
				yield return AsMethod(sourceEnum, capability.EnumName, shared);
			}
		}
	}

	private static string AsMethod(string sourceEnum, string targetEnum, List<string> brands)
	{
		var arms = string.Join("\n", brands.Select(brand => $"\t\t\t{sourceEnum}.{brand} => {targetEnum}.{brand},"));
		return $$"""
				[CompilerGenerated]
				public static {{targetEnum}} As{{targetEnum}}(this {{sourceEnum}} value) =>
					value switch
					{
			{{arms}}
					};
			""";
	}

	private static string? EnumNameFor(ImmutableArray<Capability> capabilities, int bit) =>
		capabilities.FirstOrDefault(capability => capability.Bit == bit).EnumName;

	private static List<string> BrandsWith(List<Brand> brands, int bit) =>
		brands.Where(brand => (brand.Capabilities & bit) != 0).Select(static brand => brand.Name).ToList();

	private readonly struct Brand
	{
		public Brand(string name, int capabilities, int order, string? description)
		{
			Name = name;
			Capabilities = capabilities;
			Order = order;
			Description = description;
		}

		public string Name { get; }
		public int Capabilities { get; }
		public int Order { get; }
		public string? Description { get; }
	}

	private readonly struct Capability
	{
		public Capability(int bit, string enumName)
		{
			Bit = bit;
			EnumName = enumName;
		}

		public int Bit { get; }
		public string EnumName { get; }
	}

	private readonly struct Conversion
	{
		public Conversion(int sourceBit, int targetBits)
		{
			SourceBit = sourceBit;
			TargetBits = targetBits;
		}

		public int SourceBit { get; }
		public int TargetBits { get; }
	}

	private readonly struct Matrix
	{
		public Matrix(ImmutableArray<Capability> capabilities, ImmutableArray<Conversion> conversions)
		{
			Capabilities = capabilities;
			Conversions = conversions;
		}

		public ImmutableArray<Capability> Capabilities { get; }
		public ImmutableArray<Conversion> Conversions { get; }
	}
}
