using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Roslyn.Providers;

[Generator]
public class OwnedByGenerator : IIncrementalGenerator
{
	private const string OwnedByAttributeMetadataName = "Shared.OwnedByAttribute`1";

	private const string VotesAttributeName = "Shared.VotesAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var owned = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				OwnedByAttributeMetadataName,
				static (node, _) => node is EnumMemberDeclarationSyntax,
				static (ctx, _) => Read(ctx)
			)
			.Collect();

		context.RegisterSourceOutput(owned, static (spc, members) => Emit(spc, members));
	}

	private static OwnedMember Read(GeneratorAttributeSyntaxContext context)
	{
		var member = (IFieldSymbol)context.TargetSymbol;
		var target = member.ContainingType;
		var ownerType = (INamedTypeSymbol)context.Attributes[0].AttributeClass!.TypeArguments[0];
		var ownerMembers = Members(ownerType);
		var arguments = context.Attributes[0].ConstructorArguments;
		var owner = arguments.Length > 0 ? ownerMembers.FirstOrDefault(candidate => Equals(candidate.Value, arguments[0].Value)).Name : null;
		var votes = member.GetAttributes().Any(static attribute => attribute.AttributeClass?.ToDisplayString() == VotesAttributeName);

		return new OwnedMember(
			Qualified(target),
			target.Name,
			target.ContainingNamespace.ToDisplayString(),
			Members(target).Select(static field => field.Name).ToImmutableArray(),
			Qualified(ownerType),
			ownerMembers.Select(static field => field.Name).ToImmutableArray(),
			member.Name,
			owner,
			votes
		);
	}

	private static ImmutableArray<(string Name, object? Value)> Members(INamedTypeSymbol enumType)
	{
		return enumType
			.GetMembers()
			.OfType<IFieldSymbol>()
			.Where(static field => field.HasConstantValue)
			.OrderBy(static field => Convert.ToInt64(field.ConstantValue))
			.Select(static field => (field.Name, field.ConstantValue))
			.ToImmutableArray();
	}

	private static string Qualified(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

	private static void Emit(SourceProductionContext context, ImmutableArray<OwnedMember> members)
	{
		foreach (var target in members.GroupBy(static member => member.TargetQualified))
		{
			var first = target.First();
			var byMember = target.ToDictionary(static member => member.Member);
			context.AddSource($"{first.TargetName}Owners.g.cs", SourceText.From(Build(first, byMember), Encoding.UTF8));
		}
	}

	private static string Build(OwnedMember shape, Dictionary<string, OwnedMember> byMember)
	{
		var valueSet = "global::Shared.Collections.ValueSet";
		var sb = new StringBuilder("// <auto-generated />\n#nullable enable\n#pragma warning disable CS8524\nusing System.Runtime.CompilerServices;\n\n");
		sb.Append("namespace ").Append(shape.TargetNamespace).Append(";\n\npublic static class ").Append(shape.TargetName).Append("Owners\n{\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static ")
			.Append(shape.OwnerQualified)
			.Append(" Owner(this ")
			.Append(shape.TargetQualified)
			.Append(" value) =>\n\t\tvalue switch\n\t\t{\n");
		foreach (var member in shape.TargetMembers.Where(byMember.ContainsKey).Where(member => byMember[member].Owner is not null))
		{
			sb.Append("\t\t\t").Append(shape.TargetQualified).Append('.').Append(member).Append(" => ");
			sb.Append(shape.OwnerQualified).Append('.').Append(byMember[member].Owner).Append(",\n");
		}
		sb.Append("\t\t};\n\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static bool PublishesVotes(this ").Append(shape.TargetQualified).Append(" value) =>\n\t\tvalue switch\n\t\t{\n");
		foreach (var member in shape.TargetMembers)
		{
			var votes = byMember.TryGetValue(member, out var owned) && owned.Votes;
			sb.Append("\t\t\t").Append(shape.TargetQualified).Append('.').Append(member).Append(" => ").Append(votes ? "true" : "false").Append(",\n");
		}
		sb.Append("\t\t};\n\n");

		sb.Append("\t[CompilerGenerated]\n\tpublic static ")
			.Append(valueSet)
			.Append('<')
			.Append(shape.TargetQualified)
			.Append("> Owned")
			.Append(shape.TargetName)
			.Append("s(this ")
			.Append(shape.OwnerQualified)
			.Append(" owner) =>\n\t\towner switch\n\t\t{\n");
		foreach (var owner in shape.OwnerMembers)
		{
			var owned = shape.TargetMembers.Where(member => byMember.TryGetValue(member, out var found) && found.Owner == owner);
			sb.Append("\t\t\t").Append(shape.OwnerQualified).Append('.').Append(owner).Append(" => [");
			sb.Append(string.Join(", ", owned.Select(member => $"{shape.TargetQualified}.{member}")));
			sb.Append("],\n");
		}
		sb.Append("\t\t};\n");

		sb.Append("}\n");
		return sb.ToString();
	}

	private readonly struct OwnedMember
	{
		public OwnedMember(
			string targetQualified,
			string targetName,
			string targetNamespace,
			ImmutableArray<string> targetMembers,
			string ownerQualified,
			ImmutableArray<string> ownerMembers,
			string member,
			string? owner,
			bool votes
		)
		{
			TargetQualified = targetQualified;
			TargetName = targetName;
			TargetNamespace = targetNamespace;
			TargetMembers = targetMembers;
			OwnerQualified = ownerQualified;
			OwnerMembers = ownerMembers;
			Member = member;
			Owner = owner;
			Votes = votes;
		}

		public string TargetQualified { get; }
		public string TargetName { get; }
		public string TargetNamespace { get; }
		public ImmutableArray<string> TargetMembers { get; }
		public string OwnerQualified { get; }
		public ImmutableArray<string> OwnerMembers { get; }
		public string Member { get; }
		public string? Owner { get; }
		public bool Votes { get; }
	}
}
