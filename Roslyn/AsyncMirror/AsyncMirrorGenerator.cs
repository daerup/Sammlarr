using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Roslyn.AsyncMirror;

[Generator]
public class AsyncMirrorGenerator : IIncrementalGenerator
{
	private const string GenerateAsyncAttributeMetadataName = "Shared.GenerateAsyncAttribute";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var sources = context
			.SyntaxProvider.ForAttributeWithMetadataName(
				GenerateAsyncAttributeMetadataName,
				static (node, _) => node is MethodDeclarationSyntax,
				static (ctx, _) => BuildSource(ctx)
			)
			.Where(static item => item.Source is not null)
			.Collect();

		context.RegisterSourceOutput(
			sources,
			static (spc, items) =>
			{
				var emitted = new HashSet<string>();
				foreach (var item in items)
				{
					if (item.HintName is not null && emitted.Add(item.HintName))
					{
						spc.AddSource(item.HintName, SourceText.From(item.Source!, Encoding.UTF8));
					}
				}
			}
		);
	}

	private static (string? HintName, string? Source) BuildSource(GeneratorAttributeSyntaxContext context)
	{
		if (context.TargetNode.FirstAncestorOrSelf<ClassDeclarationSyntax>() is not { } classDecl)
		{
			return (null, null);
		}

		var ns = classDecl.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().FirstOrDefault()?.Name.ToString() ?? "";
		var className = classDecl.Identifier.Text;
		var extensions = string.Join("\n", classDecl.Members.SelectMany(ExtensionBlocks));

		var source = $$"""
			// <auto-generated />
			#nullable enable
			using System;
			using System.Runtime.CompilerServices;
			using System.Threading.Tasks;

			namespace {{ns}};

			public static partial class {{className}}
			{
			{{extensions}}
			}

			""";
		return ($"{className}.AsyncMirror.g.cs", source);
	}

	private static IEnumerable<string> ExtensionBlocks(MemberDeclarationSyntax member)
	{
		if (member.Kind().ToString() != "ExtensionBlockDeclaration")
		{
			yield break;
		}

		var receiver = member.ChildNodes().OfType<ParameterListSyntax>().FirstOrDefault()?.Parameters.FirstOrDefault();
		var receiverType = receiver?.Type?.ToString();
		if (receiverType is null || receiverType.StartsWith("Task<") || receiverType.StartsWith("ValueTask<"))
		{
			yield break;
		}

		var receiverName = receiver!.Identifier.Text;
		var blockTypeParams = member.ChildNodes().OfType<TypeParameterListSyntax>().FirstOrDefault()?.ToString() ?? "";
		var blockConstraints = string.Join(" ", member.ChildNodes().OfType<TypeParameterConstraintClauseSyntax>().Select(c => c.ToString()));

		var asyncDefinitions = new List<string>();
		var allSignatures = new List<MethodInfo>();

		foreach (var method in member.ChildNodes().OfType<MethodDeclarationSyntax>().Where(IsPublic))
		{
			allSignatures.Add(SyncSignature(method));

			if (HasGenerateAsync(method) && (method.ExpressionBody is not null || method.Body is not null))
			{
				var (definition, signature) = DeriveAsync(method);
				asyncDefinitions.Add(definition);
				allSignatures.Add(signature);
			}
		}

		if (allSignatures.Count == 0)
		{
			yield break;
		}

		if (asyncDefinitions.Count > 0)
		{
			yield return ExtensionBlock(blockTypeParams, $"{receiverType} {receiverName}", blockConstraints, asyncDefinitions);
		}

		yield return MirrorBlock("Task", blockTypeParams, receiverType, blockConstraints, allSignatures);
		yield return MirrorBlock("ValueTask", blockTypeParams, receiverType, blockConstraints, allSignatures);
	}

	private static bool IsPublic(MethodDeclarationSyntax method) => method.Modifiers.Any(static m => m.IsKind(SyntaxKind.PublicKeyword));

	private static bool HasGenerateAsync(MethodDeclarationSyntax method) =>
		method.AttributeLists.SelectMany(static list => list.Attributes).Any(static a => a.Name.ToString() is "GenerateAsync" or "GenerateAsyncAttribute");

	private static MethodInfo SyncSignature(MethodDeclarationSyntax method) =>
		new(
			method.Identifier.Text,
			method.ReturnType.ToString(),
			method.TypeParameterList?.ToString() ?? "",
			method.ParameterList.ToString(),
			string.Join(" ", method.ConstraintClauses.Select(static c => c.ToString())),
			ArgNamesOf(method),
			PriorityOf(method)
		);

	private static string PriorityOf(MethodDeclarationSyntax method)
	{
		var priorities = method
			.AttributeLists.SelectMany(static list => list.Attributes)
			.Where(static a => a.Name.ToString().Split('.', ':').Last() is "OverloadResolutionPriority" or "OverloadResolutionPriorityAttribute");
		return string.Concat(priorities.Select(static a => $"[{a}] "));
	}

	private static (string Definition, MethodInfo Signature) DeriveAsync(MethodDeclarationSyntax method)
	{
		var name = method.Identifier.Text;
		var typeParams = method.TypeParameterList?.ToString() ?? "";
		var returnType = $"Task<{method.ReturnType}>";
		var constraints = string.Join(" ", method.ConstraintClauses.Select(static c => c.ToString()));
		var callbackNames = new List<string>();

		var parameters = string.Join(
			", ",
			method.ParameterList.Parameters.Select(p =>
			{
				if (p.Type is GenericNameSyntax { Identifier.Text: "Func" } generic)
				{
					callbackNames.Add(p.Identifier.Text);
					var args = generic.TypeArgumentList.Arguments;
					var last = args[args.Count - 1].ToString();
					var prefix = string.Join(", ", args.Take(args.Count - 1).Select(static a => a.ToString()));
					var wrapped = args.Count == 1 ? $"Func<Task<{last}>>" : $"Func<{prefix}, Task<{last}>>";
					return $"{wrapped} {p.Identifier.Text}";
				}
				if (p.Type is GenericNameSyntax { Identifier.Text: "Action" } action)
				{
					callbackNames.Add(p.Identifier.Text);
					var argList = string.Join(", ", action.TypeArgumentList.Arguments.Select(static a => a.ToString()));
					return $"Func<{argList}, Task> {p.Identifier.Text}";
				}
				if (p.Type is IdentifierNameSyntax { Identifier.Text: "Action" })
				{
					callbackNames.Add(p.Identifier.Text);
					return $"Func<Task> {p.Identifier.Text}";
				}
				return p.ToString();
			})
		);

		var expressionBodied = method.ExpressionBody is not null;
		var body = expressionBodied ? method.ExpressionBody!.Expression.ToString() : method.Body!.ToString();
		foreach (var callback in callbackNames)
		{
			body = body.Replace($"{callback}(", $"await {callback}(");
		}

		var constraintSuffix = string.IsNullOrEmpty(constraints) ? "" : " " + constraints;
		var priority = PriorityOf(method);
		var definition = expressionBodied
			? $"[CompilerGenerated] {priority}public async {returnType} {name}{typeParams}({parameters}){constraintSuffix} => {body};"
			: $"[CompilerGenerated] {priority}public async {returnType} {name}{typeParams}({parameters}){constraintSuffix} {body}";
		var signature = new MethodInfo(name, returnType, typeParams, $"({parameters})", constraints, ArgNamesOf(method), priority);
		return (definition, signature);
	}

	private static string MirrorBlock(string wrapper, string blockTypeParams, string receiverType, string blockConstraints, List<MethodInfo> signatures)
	{
		return ExtensionBlock(
			blockTypeParams,
			$"{wrapper}<{receiverType}> source",
			blockConstraints,
			signatures.Select(signature => MirroredMethod(wrapper, signature))
		);
	}

	private static string MirroredMethod(string wrapper, MethodInfo signature)
	{
		var returnsTask = signature.ReturnType.StartsWith("Task<");
		var returned = returnsTask ? signature.ReturnType.Substring(5, signature.ReturnType.Length - 6) : signature.ReturnType;
		var call = $"(await source).{signature.Name}({signature.ArgNames})";
		var invocation = returnsTask ? $"await {call}" : call;
		var constraintSuffix = string.IsNullOrEmpty(signature.Constraints) ? "" : " " + signature.Constraints;
		return $"[CompilerGenerated] {signature.Priority}public async {wrapper}<{returned}> {signature.Name}{signature.TypeParams}{signature.Params}{constraintSuffix} => {invocation};";
	}

	private static string ExtensionBlock(string blockTypeParams, string receiver, string blockConstraints, IEnumerable<string> members)
	{
		var constraintSuffix = string.IsNullOrEmpty(blockConstraints) ? "" : " " + blockConstraints;
		var body = string.Join("\n", members.Select(member => $"\t\t{member}"));
		return $$"""
				extension{{blockTypeParams}}({{receiver}}){{constraintSuffix}}
				{
			{{body}}
				}
			""";
	}

	private static string ArgNamesOf(MethodDeclarationSyntax method) => string.Join(", ", method.ParameterList.Parameters.Select(static p => p.Identifier.Text));

	private readonly struct MethodInfo
	{
		public MethodInfo(string name, string returnType, string typeParams, string parameters, string constraints, string argNames, string priority)
		{
			Name = name;
			ReturnType = returnType;
			TypeParams = typeParams;
			Params = parameters;
			Constraints = constraints;
			ArgNames = argNames;
			Priority = priority;
		}

		public string Name { get; }
		public string ReturnType { get; }
		public string TypeParams { get; }
		public string Params { get; }
		public string Constraints { get; }
		public string ArgNames { get; }
		public string Priority { get; }
	}
}
