using System.Collections.Immutable;
using Microsoft.CodeAnalysis;

namespace Roslyn.Options;

internal static class OptionsRegistrationSource
{
	internal const string FileName = "OptionsSectionRegistration.g.cs";

	internal static string? Generate(ImmutableArray<INamedTypeSymbol?> candidateTypes, INamedTypeSymbol markerInterface)
	{
		var discoveredTypes = CollectOptionTypes(candidateTypes, markerInterface);
		if (discoveredTypes.Count == 0)
		{
			return null;
		}

		var registrationCalls = string.Join("\n\t\t\t", discoveredTypes.Select(static t => $"services.RegisterOption<{t}>();"));

		return $$"""
			// <auto-generated />
			using Microsoft.Extensions.DependencyInjection;

			namespace Shared.Options;

			internal static class GeneratedOptionsRegistrationExtensions
			{
			    extension(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)
			    {
			        internal global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddGeneratedOptions()
			        {
			            services.AddOptions();

			            {{registrationCalls}}

			            return services;
			        }

			        private void RegisterOption<TOptions>() where TOptions : class, global::Shared.Options.IOptionsSection
			        {
			            services.AddOptions<TOptions>().BindConfiguration(TOptions.SectionName);
			            services.AddTransient(static sp => sp.GetRequiredService<global::Microsoft.Extensions.Options.IOptionsMonitor<TOptions>>().CurrentValue);
			        }
			    }
			}
			""";
	}

	private static IReadOnlyList<string> CollectOptionTypes(ImmutableArray<INamedTypeSymbol?> candidateTypes, INamedTypeSymbol markerInterface)
	{
		var discoveredTypes = new List<string>();
		var seen = new HashSet<string>(StringComparer.Ordinal);

		foreach (var candidate in candidateTypes)
		{
			if (candidate is null || candidate.IsAbstract || candidate.IsGenericType)
			{
				continue;
			}

			if (!candidate.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, markerInterface)))
			{
				continue;
			}

			var fullyQualifiedName = candidate.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
			if (seen.Add(fullyQualifiedName))
			{
				discoveredTypes.Add(fullyQualifiedName);
			}
		}

		return discoveredTypes;
	}
}
